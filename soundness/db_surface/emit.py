def block(name, d):
    lines=[]
    for t in sorted(d):
        lines.append(f'        put({name}, "{t}", "{",".join(d[t])}");')
    return '\n'.join(lines)
def setlit(s):
    s=sorted(s); return ',\n'.join('            "%s"'%x for x in s)
