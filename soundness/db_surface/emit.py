import sys,re,collections
def load(path, drop=()):
    out={}
    for l in open(path):
        t,w,lz,p,n,pure=l.rstrip('\n').split('\t')
        if t in drop: continue
        out[t.replace('/','.')]=sorted(x for x in pure.split(',') if x)
    return out
def measured(path, rx):
    # every public API type the derivation SAW, members or not (an enum has only statics), from super.tsv
    s=set()
    for l in open(path.replace('reach.tsv','super.tsv')):
        if l.startswith('#SUPER'):
            t=l.split('\t')[1]
            if re.match(rx,t): s.add(t.replace('/','.'))
    return s
